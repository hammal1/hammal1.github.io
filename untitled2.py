class AdsorptionMechanismAnalyzer:
    """تحليل آليات الامتزاز على المستوى الجزيئي"""

    def __init__(self, composition):
        self.composition = composition
        self.mechanisms = {}

    def analyze_ion_exchange(self):
        """تحليل التبادل الأيوني"""
        na = self.composition.get('Na2O', 0)
        k = self.composition.get('K2O', 0)
        al = self.composition.get('Al2O3', 0)

        # قدرة التبادل الأيوني تعتمد على Al و Na+K
        exchange_capacity = (na + k) / (al + 1) * 100
        return min(exchange_capacity, 100)

    def analyze_physical_adsorption(self):
        """تحليل الامتزاز الفيزيائي"""
        si_al = self.calculate_si_al_ratio()

        # المسامية تعتمد على Si/Al
        if 1.5 <= si_al <= 3.0:
            porosity = 30
        else:
            porosity = 15 + (si_al - 1.5) * 5

        # مساحة السطح
        surface_area = 50 + porosity * 2.5

        return {
            'porosity': min(porosity, 60),
            'surface_area': min(surface_area, 500)
        }

    def calculate_si_al_ratio(self):
        si = self.composition.get('SiO2', 0)
        al = self.composition.get('Al2O3', 0)
        return si / al if al > 0 else 0

    def analyze_chelation(self):
        """تحليل الارتباط الكيميائي (Chelation)"""
        # العناصر المشعة ترتبط مع مجموعات Si-O و Al-O
        si = self.composition.get('SiO2', 0)
        al = self.composition.get('Al2O3', 0)

        # مواقع الارتباط
        binding_sites = (si + al) / 100 * 50
        return min(binding_sites, 80)

    def analyze_radionuclide_specific(self, radionuclide):
        """تحليل امتزاز نوع معين من المواد المشعة"""

        radionuclide_data = {
            'Cs-137': {'primary': 'Na2O', 'secondary': 'Al2O3', 'mechanism': 'ion_exchange'},
            'Sr-90': {'primary': 'K2O', 'secondary': 'Al2O3', 'mechanism': 'ion_exchange'},
            'U-238': {'primary': 'Fe2O3', 'secondary': 'Al2O3', 'mechanism': 'chelation'},
            'Co-60': {'primary': 'Fe2O3', 'secondary': 'SiO2', 'mechanism': 'chelation'},
            'I-131': {'primary': 'Na2O', 'secondary': 'SiO2', 'mechanism': 'physical'}
        }

        if radionuclide not in radionuclide_data:
            return None

        data = radionuclide_data[radionuclide]
        primary = self.composition.get(data['primary'], 0)
        secondary = self.composition.get(data['secondary'], 0)

        # حساب كفاءة الامتزاز
        primary_score = min(primary / 10, 1) * 60
        secondary_score = min(secondary / 30, 1) * 40

        efficiency = primary_score + secondary_score

        return {
            'radionuclide': radionuclide,
            'mechanism': data['mechanism'],
            'primary_element': data['primary'],
            'secondary_element': data['secondary'],
            'efficiency': min(efficiency, 95)
        }

    def get_comprehensive_analysis(self, radionuclide=None):
        """تحليل شامل لآليات الامتزاز"""

        # التبادل الأيوني
        ion_exchange = self.analyze_ion_exchange()

        # الامتزاز الفيزيائي
        physical = self.analyze_physical_adsorption()

        # الارتباط الكيميائي
        chelation = self.analyze_chelation()

        # تحليل مخصص للنظير المشع
        specific = None
        if radionuclide:
            specific = self.analyze_radionuclide_specific(radionuclide)

        return {
            'ion_exchange_capacity': ion_exchange,
            'physical_adsorption': physical,
            'chelation_capacity': chelation,
            'specific_radionuclide': specific,
            'si_al_ratio': self.calculate_si_al_ratio()
        }

    def visualize_mechanisms(self, radionuclide=None):
        """تصوير آليات الامتزاز"""
        analysis = self.get_comprehensive_analysis(radionuclide)

        fig, axes = plt.subplots(2, 2, figsize=(14, 10))
        fig.suptitle('آليات امتزاز المواد المشعة في الجيوبوليمر', fontsize=14, fontweight='bold')

        # 1. آليات الامتزاز المختلفة
        mechanisms = {
            'التبادل الأيوني': analysis['ion_exchange_capacity'],
            'الامتزاز الفيزيائي': analysis['physical_adsorption']['porosity'],
            'الارتباط الكيميائي': analysis['chelation_capacity']
        }

        colors = ['#3498db', '#2ecc71', '#e74c3c']
        axes[0, 0].bar(mechanisms.keys(), mechanisms.values(), color=colors)
        axes[0, 0].set_ylabel('قدرة الامتزاز (%)')
