class GeopolymerDesignSystem:
    """النظام المتكامل لتصميم الجيوبوليمر"""

    def __init__(self):
        self.db = MaterialDatabase()
        self.predictor = AdsorptionPredictor()
        self.predictor.train()

    def design_geopolymer(self, materials, percentages, radionuclide=None):
        """تصميم الجيوبوليمر من المواد والنسب"""

        # حساب التركيب الكيميائي الكلي
        composition = {}
        for material, pct in zip(materials, percentages):
            mat_data = self.db.get_material(material)
            if mat_data:
                for oxide, value in mat_data['oxides'].items():
                    composition[oxide] = composition.get(oxide, 0) + value * pct / 100

        # محاكاة التركيب الجزيئي
        simulator = MolecularStructureSimulator(composition)
        molecular_structure = simulator.simulate_molecular_structure()

        # التنبؤ بقدرة الامتزاز
        adsorption_efficiency = self.predictor.predict(composition)

        # تحليل آليات الامتزاز
        analyzer = AdsorptionMechanismAnalyzer(composition)
        mechanisms = analyzer.get_comprehensive_analysis(radionuclide)

        return {
            'composition': composition,
            'molecular_structure': molecular_structure,
            'adsorption_efficiency': adsorption_efficiency,
            'mechanisms': mechanisms,
            'materials_used': list(zip(materials, percentages))
        }

    def optimize_composition(self, available_materials, target_efficiency=None,
                           radionuclide=None, n_iterations=1000):
        """تحسين تركيبة الجيوبوليمر"""

        def objective(percentages):
            # التأكد من أن المجموع 100%
            percentages = np.abs(percentages)
            percentages = percentages / np.sum(percentages) * 100

            composition = {}
            for material, pct in zip(available_materials, percentages):
                mat_data = self.db.get_material(material)
                if mat_data:
                    for oxide, value in mat_data['oxides'].items():
                        composition[oxide] = composition.get(oxide, 0) + value * pct / 100

            # حساب الكفاءة
            efficiency = self.predictor.predict(composition)

            # إذا كان هناك هدف محدد
            if target_efficiency:
                return -min(efficiency, target_efficiency)  # تقليل الفرق
            else:
                return -efficiency  # نريد تعظيم الكفاءة

        # التحسين
        n = len(available_materials)
        initial = np.ones(n) / n * 100

        result = minimize(objective, initial, method='Nelder-Mead',
                         options={'maxiter': n_iterations})

        # استخراج النسب المثلى
        optimal_percentages = np.abs(result.x)
        optimal_percentages = optimal_percentages / np.sum(optimal_percentages) * 100

        return self.design_geopolymer(available_materials, optimal_percentages, radionuclide)

    def generate_report(self, design_result, radionuclide=None):
        """توليد تقرير علمي شامل"""

        report = []
        report.append("=" * 80)
        report.append("تقرير تصميم الجيوبوليمر لامتصاص المواد المشعة")
        report.append("=" * 80)

        # 1. المواد المستخدمة
        report.append("\n1. المواد المستخدمة:")
        for material, pct in design_result['materials_used']:
            report.append(f"   - {material}: {pct:.1f}%")

        # 2. التركيب الكيميائي
        report.append("\n2. التركيب الكيميائي المتوقع:")
        for oxide, value in sorted(design_result['composition'].items(),
                                  key=lambda x: x[1], reverse=True):
            if value > 0.5:
                report.append(f"   - {oxide}: {value:.2f}%")

        # 3. البنية الجزيئية
        struct = design_result['molecular_structure']
        report.append(f"\n3. البنية الجزيئية:")
        report.append(f"   - النوع: {struct['type']}")
        report.append(f"   - الوصف: {struct['description']}")
        report.append(f"   - نسبة Si/Al: {struct['si_al_ratio']:.2f}")
        report.append(f"   - المسامية: {struct['porosity']:.1f}%")
        report.append(f"   - مساحة السطح: {struct['surface_area']:.1f} m²/g")

        # 4. قدرة الامتزاز
        report.append(f"\n4. قدرة الامتزاز:")
        report.append(f"   - الكفاءة المتوقعة: {design_result['adsorption_efficiency']:.1f}%")

        # 5. آليات الامتزاز
        mech = design_result['mechanisms']
        report.append(f"\n5. آليات الامتزاز:")
        report.append(f"   - التبادل الأيوني: {mech['ion_exchange_capacity']:.1f}%")
        report.append(f"   - الامتزاز الفيزيائي: {mech['physical_adsorption']['porosity']:.1f}%")
        report.append(f"   - الارتباط الكيميائي: {mech['chelation_capacity']:.1f}%")

        if radionuclide and mech['specific_radionuclide']:
            spec = mech['specific_radionuclide']
            report.append(f"\n6. امتزاز {radionuclide}:")
            report.append(f"   - الكفاءة: {spec['efficiency']:.1f}%")
            report.append(f"   - الآلية الرئيسية: {spec['mechanism']}")

        # 7. التوصيات
        report.append("\n7. التوصيات:")
        if design_result['adsorption_efficiency'] > 80:
            report.append("   ✅ التركيبة ممتازة للامتزاز الإشعاعي")
        elif design_result['adsorption_efficiency'] > 60:
            report.append("   ✅ التركيبة جيدة - يمكن تحسينها بإضافة:")
            if design_result['composition'].get('Al2O3', 0) < 20:
                report.append("      - زيادة الألومينا (ميتاكاولين أو بنتونايت)")
            if design_result['composition'].get('Na2O', 0) < 3:
                report.append("      - زيادة الصوديوم (زيوليت)")
        else:
            report.append("   ⚠️ يحتاج إلى تحسين كبير:")
            report.append("      - إضافة مواد ذات مساحة سطح عالية (زيوليت، بنتونايت)")
            report.append("      - تحسين نسبة Si/Al لتكون بين 1.5 - 3.0")

        report.append("\n" + "=" * 80)

        return "\n".join(report)

